function escapeHtml(value = '') {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function escapeAttr(value = '') {
  return escapeHtml(value).replace(/'/g, '&#39;')
}

function ensureDir(filePath) {
  mkdirSync(dirname(filePath), { recursive: true })
}

function targetForPath(path) {
  const normalized = normalizePath(path)

  if (normalized === '/') {
    return resolve(dist, 'index.html')
  }

  if (normalized.endsWith('.html')) {
    return resolve(dist, normalized.slice(1))
  }

  return resolve(dist, normalized.slice(1), 'index.html')
}

function titleFor(page) {
  return page.seoTitle || (page.title === SITE.name ? SITE.name : `${page.title} — ${SITE.name}`)
}

function imageFor(page) {
  return absoluteUrl(page.image || SITE.defaultImage)
}

function imageAltFor(page) {
  return page.imageAlt || SITE.defaultImageAlt
}

function robotsContent(noindex = false) {
  return noindex ? 'noindex, follow' : 'index, follow'
}

function seoHead(page, jsonLd = [], options = {}) {
  const title = titleFor(page)
  const description = page.description || SITE.defaultDescription
  const canonical = canonicalUrl(page.path)
  const ogType = page.type === 'Article' || page.articleType ? 'article' : 'website'
  const image = imageFor(page)
  const imageAlt = imageAltFor(page)
  const keywords = page.keywords?.length ? page.keywords.join(', ') : ''
  const jsonLdItems = Array.isArray(jsonLd) ? jsonLd : [jsonLd]

  return `<!-- SEO: generated by scripts/build-seo.mjs -->
<title>${escapeHtml(title)}</title>
<meta name="description" content="${escapeAttr(description)}" />
<meta name="author" content="${escapeAttr(SITE.author)}" />
<meta name="robots" content="${robotsContent(options.noindex)}" />
${keywords ? `<meta name="keywords" content="${escapeAttr(keywords)}" />` : ''}
<meta name="theme-color" content="${escapeAttr(SITE.themeColor)}" />
<link rel="canonical" href="${escapeAttr(canonical)}" />
<link rel="icon" type="image/svg+xml" href="/favicon.svg" />
<link rel="apple-touch-icon" href="/favicon.svg" />
<link rel="manifest" href="/manifest.webmanifest" />
<meta property="og:title" content="${escapeAttr(title)}" />
<meta property="og:description" content="${escapeAttr(description)}" />
<meta property="og:type" content="${escapeAttr(ogType)}" />
<meta property="og:url" content="${escapeAttr(canonical)}" />
<meta property="og:site_name" content="${escapeAttr(SITE.name)}" />
<meta property="og:image" content="${escapeAttr(image)}" />
<meta property="og:image:alt" content="${escapeAttr(imageAlt)}" />
<meta name="twitter:card" content="summary_large_image" />
<meta name="twitter:title" content="${escapeAttr(title)}" />
<meta name="twitter:description" content="${escapeAttr(description)}" />
<meta name="twitter:image" content="${escapeAttr(image)}" />
${jsonLdItems.map((item) => `<script type="application/ld+json">${JSON.stringify(item)}</script>`).join('\n')}
<!-- /SEO -->`
}

function stripExistingSeo(head) {
  return head
    .replace(/\s*<!-- SEO: generated by scripts\/build-seo\.mjs -->[\s\S]*?<!-- \/SEO -->/gi, '')
    .replace(/\s*<title>[\s\S]*?<\/title>/gi, '')
    .replace(/\s*<meta\s+name=["']description["'][^>]*>\s*/gi, '')
    .replace(/\s*<meta\s+name=["']author["'][^>]*>\s*/gi, '')
    .replace(/\s*<meta\s+name=["']robots["'][^>]*>\s*/gi, '')
    .replace(/\s*<meta\s+name=["']keywords["'][^>]*>\s*/gi, '')
    .replace(/\s*<meta\s+name=["']theme-color["'][^>]*>\s*/gi, '')
    .replace(/\s*<link\s+rel=["']canonical["'][^>]*>\s*/gi, '')
    .replace(/\s*<link\s+rel=["']icon["'][^>]*>\s*/gi, '')
    .replace(/\s*<link\s+rel=["']apple-touch-icon["'][^>]*>\s*/gi, '')
    .replace(/\s*<link\s+rel=["']manifest["'][^>]*>\s*/gi, '')
    .replace(/\s*<meta\s+(?:property|name)=["']og:[^"']+["'][^>]*>\s*/gi, '')
    .replace(/\s*<meta\s+name=["']twitter:[^"']+["'][^>]*>\s*/gi, '')
    .replace(/\s*<script\s+type=["']application\/ld\+json["'][\s\S]*?<\/script>\s*/gi, '')
}

function injectSeo(html, page, jsonLd, options = {}) {
  return html.replace(/<head>([\s\S]*?)<\/head>/i, (_, head) => {
    let cleanHead = stripExistingSeo(head)
    const leading = []

    for (const pattern of [
      /\s*<meta\s+charset=["'][^"']+["']\s*\/?>\s*/i,
      /\s*<meta\s+name=["']viewport["'][^>]*>\s*/i,
    ]) {
      const match = cleanHead.match(pattern)
      if (match) {
        leading.push(match[0].trim())
        cleanHead = cleanHead.replace(pattern, '\n')
      }
    }

    return `<head>
${leading.join('\n')}
${seoHead(page, jsonLd, options)}
${cleanHead.trimStart()}</head>`
  })
}

