function webPageJsonLd(page) {
  return {
    '@context': 'https://schema.org',
    '@type': 'WebPage',
    '@id': `${canonicalUrl(page.path)}#webpage`,
    url: canonicalUrl(page.path),
    name: titleFor(page),
    description: page.description || SITE.defaultDescription,
    isPartOf: { '@id': `${SITE.url}/#website` },
    author: { '@id': `${SITE.url}/#person` },
    publisher: { '@id': `${SITE.url}/#person` },
    inLanguage: SITE.language,
  }
}

function homeJsonLd() {
  return {
    '@context': 'https://schema.org',
    '@graph': [websiteJsonLd(), personJsonLd()],
  }
}

function articleJsonLd(item) {
  return {
    '@context': 'https://schema.org',
    '@type': item.articleType || 'Article',
    '@id': `${canonicalUrl(item.path)}#article`,
    headline: item.title,
    description: item.description,
    author: {
      '@type': 'Person',
      name: SITE.author,
      url: SITE.url,
    },
    publisher: {
      '@type': 'Person',
      name: SITE.author,
      url: SITE.url,
    },
    datePublished: item.datePublished,
    dateModified: item.dateModified || item.datePublished,
    mainEntityOfPage: canonicalUrl(item.path),
    image: imageFor(item),
    articleSection: item.category,
    keywords: item.keywords?.join(', '),
    inLanguage: SITE.language,
  }
}

function productJsonLd(product) {
  const base = {
    '@context': 'https://schema.org',
    '@type': product.schemaType || 'WebPage',
    '@id': `${canonicalUrl(product.path)}#${product.schemaType || 'webpage'}`,
    name: product.title,
    url: canonicalUrl(product.path),
    description: product.description,
    author: {
      '@type': 'Person',
      name: SITE.author,
      url: SITE.url,
    },
    keywords: product.keywords?.join(', '),
    inLanguage: SITE.language,
  }

  if (product.schemaType === 'SoftwareApplication') {
    return {
      ...base,
      applicationCategory: product.applicationCategory || 'ProductivityApplication',
      operatingSystem: 'Web, iOS, Android',
    }
  }

  return base
}

