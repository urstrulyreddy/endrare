function copyStandalonePage(page) {
  if (page.redirectTo) { writeRoute(page, redirectLayout(page.path, page.redirectTo, getPageById('contact'))); return }
  const source = resolve(root, page.sourceFile)
  if (!existsSync(source)) {
    throw new Error(`${page.title} file not found: ${source}`)
  }

  const raw = refreshStandalone(readFileSync(source, 'utf8'), page)
  const jsonLd = page.articleType ? [articleJsonLd(page)] : [webPageJsonLd(page)]
  const html = injectSeo(raw, page, jsonLd)
  const targets = [page.path].map(targetForPath)

  for (const target of targets) {
    ensureDir(target)
    writeFileSync(target, html)
  }

  for (const legacyPath of page.legacyPaths || []) {
    const target = targetForPath(legacyPath)
    ensureDir(target)
    writeFileSync(target, redirectLayout(legacyPath, page.path, page))
  }
}

function writeRoute(page, html) {
  const target = targetForPath(page.path)
  ensureDir(target)
  writeFileSync(target, html)
}

async function patchHomePage() {
  const home = getPageById('home')
  const playground = getPageById('playground')
  const target = targetForPath('/')
  const stage = mkdtempSync(resolve(root, 'node_modules/.endrare-prerender-'))
  try {
    await build({ configFile:false, logLevel:'error', build:{ ssr:resolve(root,'src/App.jsx'), outDir:stage, emptyOutDir:true, minify:false, rollupOptions:{output:{entryFileNames:'app.mjs'}} } })
    const { default: App } = await import(pathToFileURL(resolve(stage,'app.mjs')).href)
    const template = readFileSync(target, 'utf8')
    const renderRoute = (page, pathname, jsonLd) => {
      const html = template.replace('<div id="root"></div>', `<div id="root">${renderToString(React.createElement(App, { pathname }))}</div>`)
      const routeTarget = targetForPath(page.path)
      ensureDir(routeTarget)
      writeFileSync(routeTarget, injectSeo(html, page, jsonLd))
    }
    renderRoute(home, '/', [homeJsonLd()])
    if (playground) renderRoute(playground, playground.path, [webPageJsonLd(playground)])
  } finally { rmSync(stage, {recursive:true,force:true}) }
}

function writeSitemap() {
  const seen = new Map()

  for (const page of getAllSitemapPages()) {
    seen.set(normalizePath(page.path), page)
  }

  const entries = [...seen.values()]
  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries.map((page) => `  <url>
    <loc>${escapeHtml(canonicalUrl(page.path))}</loc>
    <lastmod>${page.dateModified || page.datePublished || today}</lastmod>
    ${page.changefreq ? `<changefreq>${page.changefreq}</changefreq>` : ''}
    ${page.priority ? `<priority>${page.priority}</priority>` : ''}
  </url>`).join('\n')}
</urlset>
`

  writeFileSync(resolve(dist, 'sitemap.xml'), xml)
}

